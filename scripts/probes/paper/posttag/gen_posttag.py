"""gen_posttag.py SRC_QUEUE OUT_QUEUE -- D145 post-tag: the evidence queue for the 10/18 tag, generated from D145's
pre-registered run lines (B1, B2, B3, B8, B9, B10; held lines included), with the tag's code copies in place of the
deliverable's (repo_d145 -> repo_t, repo_d145s -> repo_ts) and new folders (d145_bN -> d145t_bN); B7 = RG97 on bunny and
dragon on repo_tgf (gradient dump and lambda = 0 counterfactual at every window, full archive, J read: EVAL jv), in
place of G97 / RG97 / JV97. Order: B1 seed 97 (six meshes, L and P), B7, B1 seeds 99 / 101, B1 bunny / dragon 103 / 105,
B2, B8, B9, B10, B3 (40k), B1's every-frame readings. Prints the per-group counts."""
import collections
import sys

src, out = sys.argv[1], sys.argv[2]
G = "/data/relcfd/chayo/physmorph_v2/output/gpu"
REPO = {"repo_d145": "repo_t", "repo_d145s": "repo_ts"}
lines, seen = [], set()
for raw in open(src):
    s = raw.rstrip("\n")
    if s.startswith("#HOLD-posttag "):
        s = s[len("#HOLD-posttag "):]
    if not s or s.startswith("#"):
        continue
    f = s.split()
    name, mesh, n, repo, d = f[:5]
    if d not in ("d145_b1", "d145_b2", "d145_b3", "d145_b8", "d145_b9", "d145_b10"):
        continue
    if (name, d) in seen:
        continue
    seen.add((name, d))
    nd = d.replace("d145_", "d145t_")
    if mesh == "job":
        if not name.startswith("full_"):
            continue
        lines.append(("B1full", s.replace(" " + d + " ", " " + nd + " ")))
        continue
    if repo not in REPO:
        continue
    f[3], f[4] = REPO[repo], nd
    key = {"d145_b1": "B1", "d145_b2": "B2", "d145_b3": "B3", "d145_b8": "B8", "d145_b9": "B9", "d145_b10": "B10"}[d]
    if key == "B1":
        seed = name.rstrip("0123456789")
        sd = name[len(seed):]
        key = {"97": "B1s97", "99": "B1s", "101": "B1s"}.get(sd, "B1x")
    lines.append((key, " ".join(f)))
CF = ",".join(str(i) for i in range(400))
b7 = [f"{m}300k_RG97 {m} 300000 repo_tgf d145t_b7 jv 1 --seed 97 --grad_dump {G}/d145t_b7/{m}300k_RG97_dump "
      f"--dump_windows 0,+1 --cf_dir {G}/d145t_b7/{m}300k_RG97_cf --cf_windows {CF}" for m in ("bunny", "dragon")]
order = ["B1s97", "B7", "B1s", "B1x", "B2", "B8", "B9", "B10", "B3", "B1full"]
groups = collections.defaultdict(list)
for k, s in lines:
    groups[k].append(s)
groups["B7"] = b7
with open(out, "w") as fo:
    fo.write("# === D145 post-tag evidence queue (generated by gen_posttag.py; appended by posttag_watch.sh after the gate) ===\n")
    for k in order:
        fo.write(f"# --- {k}: {len(groups[k])} items\n")
        for s in groups[k]:
            fo.write(s + "\n")
for k in order:
    print(k, len(groups[k]))
